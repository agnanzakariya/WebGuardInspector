using System.Text.Json.Serialization;
using WebGuard.Core.Detection;
using WebGuard.Core.Findings;
using WebGuard.Core.Scanning;

namespace WebGuard.Core.Fixing;

/// <summary>What the AI concluded about a finding it was asked to fix.</summary>
[JsonConverter(typeof(JsonStringEnumConverter<FixVerdict>))]
public enum FixVerdict { Fix, FalsePositive, CannotFix }

/// <summary>
/// One exact text replacement. <see cref="OldText"/> is copied from the redacted file the model saw, so it may
/// contain <see cref="SourceRedactor.Mask"/> where a secret was; <see cref="FixPatcher"/> matches those parts as wildcards.
/// </summary>
public sealed record CodeEdit(string OldText, string NewText);

/// <summary>Lines of a large file sent to the model instead of the whole file (1-based, inclusive).</summary>
public sealed record FileExcerpt(int FirstLine, int LastLine, int TotalLines);

/// <summary>
/// Everything the fixer sees: the finding and the file to change, already redacted. Never the original secrets.
/// For a large file only <see cref="Excerpt"/> lines are sent; for a dependency reported in a lockfile the file to
/// change is the manifest (<see cref="Dependency"/>), and the lockfile is regenerated by a command the person runs.
/// </summary>
/// <param name="TargetPath">File the edits apply to when it is not the finding's own file (the manifest).</param>
public sealed record FixRequest(
    SecurityFinding Finding,
    string RedactedFileContent,
    IReadOnlyList<SecurityFinding> OtherFindingsInFile,
    string? TargetPath = null,
    FileExcerpt? Excerpt = null,
    DependencyFixPlan? Dependency = null)
{
    /// <summary>Relative path of the file the proposed edits apply to.</summary>
    public string EditPath => TargetPath ?? Finding.Location.RelativePath;
}

public static class FixRequestBuilder
{
    /// <summary>Upper bound on the redacted text sent to the model; larger files are sent as an excerpt.</summary>
    public const int MaxContentChars = 200_000;

    /// <summary>Lines sent above and below the reported lines of a large file.</summary>
    public const int ExcerptRadius = 200;

    /// <summary>Upper bound on an excerpt (long minified lines make a few hundred lines large).</summary>
    public const int MaxExcerptChars = 60_000;

    /// <summary>
    /// Builds what the model sees for <paramref name="finding"/>, reading files strictly inside <paramref name="scope"/>:
    /// the redacted file; an excerpt around the reported lines when the file is too large; or, for a vulnerable
    /// dependency in a lockfile, the manifest next to it plus the regenerate command. Fails for files that cannot be
    /// patched (binary, not UTF-8, or too large with no line to excerpt), so they are reported without asking the model.
    /// </summary>
    public static bool TryBuild(ProjectScope scope, SecurityFinding finding, IEnumerable<SecurityFinding> allFindings,
        out FixRequest request, out string error)
    {
        ArgumentNullException.ThrowIfNull(finding);
        ArgumentNullException.ThrowIfNull(allFindings);
        request = null!;

        if (DependencyFixPlan.TryCreate(finding, out var plan))
        {
            // The lockfile itself is never edited. Without a manifest the answer is just the command.
            var manifest = string.Empty;
            if (SourceFile.TryRead(scope, plan.ManifestPath, out var manifestFile, out _))
            {
                manifest = SourceRedactor.Redact(manifestFile.Text, manifestFile.FullPath);
                if (manifest.Length > MaxContentChars) manifest = string.Empty;
            }
            request = new FixRequest(finding, manifest, [], plan.ManifestPath, null, plan);
            error = string.Empty;
            return true;
        }

        if (!SourceFile.TryRead(scope, finding.Location.RelativePath, out var file, out error)) return false;
        var others = allFindings
            .Where(f => f.Id != finding.Id && string.Equals(f.Location.RelativePath, finding.Location.RelativePath, StringComparison.OrdinalIgnoreCase))
            .Take(20)
            .ToArray();
        var redacted = SourceRedactor.Redact(file.Text, file.FullPath);
        if (redacted.Length <= MaxContentChars)
        {
            request = new FixRequest(finding, redacted, others);
            return true;
        }

        if (finding.Location.StartLine <= 0)
        {
            error = $"The file has {redacted.Length:N0} characters (limit {MaxContentChars:N0}) and the finding has no line number to cut an excerpt around.";
            return false;
        }
        var lines = file.Text.Split('\n');
        var start = Math.Min(finding.Location.StartLine, lines.Length);
        var end = Math.Min(Math.Max(start, finding.Location.EndLine), lines.Length);
        for (var radius = ExcerptRadius; radius >= 10; radius /= 2)
        {
            var first = Math.Max(1, start - radius);
            var last = Math.Min(lines.Length, end + radius);
            var excerpt = SourceRedactor.Redact(string.Join('\n', lines[(first - 1)..last]), file.FullPath);
            if (excerpt.Length > MaxExcerptChars) continue;
            request = new FixRequest(finding, excerpt, others, null, new FileExcerpt(first, last, lines.Length));
            return true;
        }
        error = $"The lines around the finding are longer than {MaxExcerptChars:N0} characters (minified code?); fix this file by hand.";
        return false;
    }
}

/// <summary>
/// AI output: a hypothesis with proposed edits. Nothing is written until a person applies it.
/// <see cref="FollowUpCommand"/> (e.g. regenerating a lockfile) is shown for the person to run; Azura never runs it.
/// </summary>
public sealed record FixProposal(
    Guid FindingId,
    string Model,
    FixVerdict Verdict,
    string Explanation,
    IReadOnlyList<CodeEdit> Edits,
    Confidence Confidence,
    DateTimeOffset CreatedAtUtc,
    string? FollowUpCommand = null);

public interface ICodeFixer
{
    string DisplayName { get; }
    Task<EngineStatus> GetStatusAsync(CancellationToken cancellationToken);
    Task<FixProposal> ProposeAsync(FixRequest request, CancellationToken cancellationToken);
}
